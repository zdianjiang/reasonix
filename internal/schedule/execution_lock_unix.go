//go:build !windows

package schedule

import (
	"errors"
	"os"
	"path/filepath"
	"syscall"
)

// tryExecutionLock prevents two bot processes sharing a state directory from
// executing the same due task concurrently. The kernel releases flock locks if
// a process exits, so a crashed scheduler cannot leave a stale lease behind.
func tryExecutionLock(path string) (release func(), acquired bool, err error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return nil, false, err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, false, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		_ = f.Close()
		if errors.Is(err, syscall.EWOULDBLOCK) || errors.Is(err, syscall.EAGAIN) {
			return nil, false, nil
		}
		return nil, false, err
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, true, nil
}
